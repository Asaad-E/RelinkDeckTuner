"""Embed the compiled replacement pixel shaders into upscale_shaders.h (called by build.bat)."""
import os

os.chdir(os.path.dirname(os.path.abspath(__file__)))


def arr(name, path):
    b = open(path, "rb").read()
    lines = [", ".join("0x%02x" % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return "static const unsigned char %s[] = {\n    %s\n};\n" % (name, ",\n    ".join(lines))


with open("upscale_shaders.h", "w") as f:
    f.write("// Generated by build.bat from easu_ps.hlsl and upscale_ps.hlsl. Do not edit.\n#pragma once\n")
    f.write(arr("kEasuPS", "build/easu_ps.cso"))
    f.write(arr("kBicubicPS", "build/upscale_ps.cso"))
